#3-Faça um algoritmo que receba um número e mostre uma mensagem caso este
#  número seja  maior que 80, menor que 25 ou igual a 40. 
numero = int(input("digite um numero:"))

if numero > 80:
        print("O numero digitado e maior que 80")
elif numero < 25:
        print("O numero digitado e menor que 25")
elif numero == 40:
        print("O numero digitado e igual a 40")